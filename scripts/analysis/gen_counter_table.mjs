// Generates src/film/data/counterRewind.ts from reference/analysis/counter_reference.tsv.
// Usage: node scripts/analysis/gen_counter_table.mjs
import { readFileSync, writeFileSync } from "node:fs";

const rows = readFileSync("reference/analysis/counter_reference.tsv", "utf8")
  .trim()
  .split("\n")
  .slice(1)
  .map((l) => l.split("\t"));
const rewind = rows.filter((r) => r[2] === "rewind");
const from = Number(rewind[0][0]);
rewind.forEach((r, i) => {
  if (Number(r[0]) !== from + i) throw new Error(`gap at ${r[0]}`);
});
const values = rewind.map((r) => Number(r[1]));
const lines = [];
for (let i = 0; i < values.length; i += 16) {
  lines.push("  " + values.slice(i, i + 16).join(", ") + ",");
}
writeFileSync(
  "src/film/data/counterRewind.ts",
  `// GENERATED by scripts/analysis/gen_counter_table.mjs — do not edit.
// Counter value shown in reference.mp4 for global frames [${from}, ${from + values.length}),
// read by template OCR (scripts/analysis/counter_ocr.py). Frame 3885 is low confidence (±1).
export const COUNTER_REWIND_FROM = ${from};
export const COUNTER_REWIND: readonly number[] = [
${lines.join("\n")}
];
`,
);
console.log(`wrote ${values.length} values from ${from}`);
